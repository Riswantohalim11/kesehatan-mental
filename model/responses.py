# Duplicate aliases inside RESPONSES dictionary for direct lookup
for _alias, _target in EMOTION_ALIASES.items():
    if _target in RESPONSES and _alias not in RESPONSES:
        RESPONSES[_alias] = RESPONSES[_target]

def get_response(emotion_label, topic_label):
    norm_emotion = EMOTION_ALIASES.get(emotion_label, emotion_label)
    if norm_emotion in RESPONSES:
        if topic_label in RESPONSES[norm_emotion]:
            return random.choice(RESPONSES[norm_emotion][topic_label])
        # Fallback to 'Umum' if topic not found
        if 'Umum' in RESPONSES[norm_emotion]:
            return random.choice(RESPONSES[norm_emotion]['Umum'])
    
    # Absolute fallback
    return "Saya mendengar Anda. Bisakah Anda menceritakan lebih lanjut tentang perasaan ini?"


